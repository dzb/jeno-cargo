package com.jujin.mjm.cli;

import java.io.IOException;
import java.io.InputStream;
import java.util.Properties;

/**
 * mjm's version, derived from the build — never hand-maintained in source.
 *
 * <p>One declaration, two derived forms (DESIGN.md §7.5):
 * <ul>
 *   <li>{@code mjm.toml [project].version} — the single human-authored value</li>
 *   <li>{@code META-INF/mjm/version.properties} — generated at build time,
 *       readable from {@code target/classes}, a jar, and the installed dist
 *       alike (the resource path is the only one that survives all three)</li>
 *   <li>{@code Implementation-Version} in the jar manifest — the Java-native
 *       spelling, so outside tools and IDEs see the version too</li>
 * </ul>
 *
 * <p>Why a resource and not just the manifest: {@code
 * Package.getImplementationVersion()} answers {@code null} when classes are
 * read from a directory rather than a jar — and CI's version gate runs
 * exactly that way ({@code java -cp target/classes ...}). The manifest is
 * kept because it is the Java convention, but the resource is what actually
 * carries the value in every layout.
 *
 * <p>There is no embedded fallback: the build always writes the resource
 * before compiling, so a binary that cannot find it was not built by mjm. That
 * case reports {@link #UNKNOWN} rather than inventing a number — a wrong
 * version is worse than an honest {@code dev}.
 */
public final class Version {

    /** The resource path the build writes. */
    static final String RESOURCE = "/META-INF/mjm/version.properties";

    /** Reported when the resource is absent — a binary mjm did not build. */
    static final String UNKNOWN = "dev";

    private static final String CURRENT = resolve();

    private Version() {}

    /** The running mjm's version, or {@link #UNKNOWN} when the build wrote none. */
    public static String current() {
        return CURRENT;
    }

    private static String resolve() {
        String fromResource = readResource();
        return fromResource == null || fromResource.isBlank()
                ? UNKNOWN : fromResource.strip();
    }

    private static String readResource() {
        try (InputStream in = Version.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                return null;
            }
            Properties properties = new Properties();
            properties.load(in);
            return properties.getProperty("version");
        } catch (IOException e) {
            return null;
        }
    }

    /**
     * The resource's text as the build writes it. Kept here so the writer and
     * the reader agree on the format in one place.
     */
    public static String propertiesText(String version) {
        return "# generated by mjm — one declaration, derived here (do not edit)\n"
                + "version=" + version + "\n";
    }
}
