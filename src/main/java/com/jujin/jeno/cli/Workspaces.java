package com.jujin.jeno.cli;

import com.jujin.freeway.commons.toml.TomlUtils;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import com.jujin.jeno.project.JenoProject;
import com.jujin.jeno.project.ProjectReader;
import com.jujin.jeno.project.Requirement;
import com.jujin.jeno.project.SchemaSource;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.TreeMap;

/**
 * {@code jeno.ws.toml} — the local workspace file, read from the nearest
 * directory at or above the project.
 *
 * <pre>
 * # generated by jeno init --ws — a local file, not meant to be committed
 * [ws]
 * modules = ["libs/core", "apps/web"]
 * </pre>
 *
 * <p>Paths are relative to the file's directory and are not a topological
 * order — the resolver, not the file, decides who depends on whom. A workspace
 * root is not itself a module: one directory cannot be both.
 *
 * <p>Reading walks up from the project and takes the <em>nearest</em> file, so a
 * nested workspace shadows an outer one. No file means no workspace.
 */
public final class Workspaces {

    /** The file name every workspace is defined by. */
    public static final String FILE = "jeno.ws.toml";

    /** A parsed workspace: where its file lives and the modules it lists. */
    public record Workspace(Path root, Path file, List<Path> modules) {}

    private Workspaces() {}

    /** The nearest workspace at or above {@code start}, or empty when there is none. */
    public static Optional<Workspace> read(Path start) {
        Path dir = start.toAbsolutePath().normalize();
        while (dir != null) {
            Path file = dir.resolve(FILE);
            if (Files.isRegularFile(file)) {
                return Optional.of(parse(dir, file));
            }
            Path legacy = dir.resolve(LegacyNames.WORKSPACE);
            if (Files.isRegularFile(legacy)) {
                throw new LegacyNames.LegacyException(LegacyNames.workspace(dir));
            }
            dir = dir.getParent();
        }
        return Optional.empty();
    }

    /** The id a module is addressed by, the same convention native artifacts use. */
    public static String moduleId(JenoProject project) {
        return project.group() == null || project.group().isBlank()
                ? project.name()
                : project.group() + ":" + project.name();
    }

    /** The workspace whose root is exactly {@code projectDir}, or empty. */
    public static Optional<Workspace> rootAt(Path projectDir) {
        Path real;
        try {
            real = projectDir.toRealPath();
        } catch (IOException e) {
            return Optional.empty();
        }
        return read(projectDir).filter(workspace -> workspace.root().equals(real));
    }

    /**
     * The modules in dependency order: a module that another one declares comes
     * first. Ties are broken by path so the order is stable, not derived from
     * file order — the workspace file deliberately carries no order at all.
     */
    public static List<Path> topological(Workspace workspace) {
        Map<Path, Set<Path>> edges = new TreeMap<>();
        Map<String, Path> idToModule = new HashMap<>();
        for (Path module : workspace.modules()) {
            edges.put(module, new LinkedHashSet<>());
            idToModule.put(moduleId(readProject(module, workspace)), module);
        }
        for (Path module : workspace.modules()) {
            JenoProject project = readProject(module, workspace);
            for (String id : declaredIds(project)) {
                Path dependency = idToModule.get(id);
                if (dependency != null && !dependency.equals(module)) {
                    edges.get(dependency).add(module);  // dependency before dependent
                }
            }
        }

        List<Path> ordered = new ArrayList<>();
        Set<Path> placed = new LinkedHashSet<>();
        while (ordered.size() < edges.size()) {
            List<Path> ready = edges.keySet().stream()
                    .filter(module -> !placed.contains(module))
                    .filter(module -> edges.entrySet().stream()
                            .filter(entry -> entry.getValue().contains(module))
                            .allMatch(entry -> placed.contains(entry.getKey())))
                    .toList();
            if (ready.isEmpty()) {
                throw new WorkspaceException("workspace modules form a dependency cycle: "
                        + cycle(edges, placed, workspace));
            }
            ordered.addAll(ready);
            placed.addAll(ready);
        }
        return List.copyOf(ordered);
    }

    /** One cycle, as {@code a -> b -> a}, for the error message. */
    private static String cycle(Map<Path, Set<Path>> edges, Set<Path> placed,
                                Workspace workspace) {
        for (Path start : edges.keySet()) {
            if (placed.contains(start)) {
                continue;
            }
            List<Path> found = new ArrayList<>();
            java.util.Deque<Path> stack = new java.util.ArrayDeque<>();
            if (walkCycle(start, edges, placed, stack, found)) {
                List<String> shown = new ArrayList<>();
                for (Path module : found) {
                    shown.add(display(workspace.root(), module));
                }
                return String.join(" -> ", shown);
            }
        }
        return "(unresolved)";
    }

    private static boolean walkCycle(Path node, Map<Path, Set<Path>> edges, Set<Path> placed,
                                     java.util.Deque<Path> stack, List<Path> found) {
        if (stack.contains(node)) {
            List<Path> slice = new ArrayList<>(stack);
            found.addAll(slice.subList(slice.indexOf(node), slice.size()));
            found.add(node);
            return true;
        }
        stack.addLast(node);
        for (Path next : edges.getOrDefault(node, Set.of())) {
            if (placed.contains(next)) {
                continue;
            }
            if (walkCycle(next, edges, placed, stack, found)) {
                return true;
            }
        }
        stack.removeLast();
        return false;
    }

    private static List<String> declaredIds(JenoProject project) {
        List<String> ids = new ArrayList<>();
        for (Requirement requirement : project.requirements()) {
            ids.add(requirement.id());
        }
        for (Requirement requirement : project.devRequirements()) {
            ids.add(requirement.id());
        }
        for (Requirement requirement : project.processorRequirements()) {
            ids.add(requirement.id());
        }
        return ids;
    }

    private static JenoProject readProject(Path module, Workspace workspace) {
        return readProject(workspace.root(), module);
    }

    private static JenoProject readProject(Path root, Path module) {
        String legacy = ProjectFiles.legacyProblem(module);
        if (legacy != null) {
            throw new LegacyNames.LegacyException(legacy);
        }
        try {
            return ProjectReader.parse(Files.readString(module.resolve("jeno.toml")));
        } catch (IOException | RuntimeException e) {
            throw new WorkspaceException("cannot read " + display(root, module)
                    + "/jeno.toml — " + e.getMessage());
        }
    }

    /** {@code file:line:column: } — the prefix every workspace schema error carries. */
    private static String at(Path file, SchemaSource.Site site) {
        return site == null ? file + ": "
                : file + ":" + site.line() + ":" + site.column() + ": ";
    }

    /** A module path as the workspace file spells it: relative, forward slashes. */
    static String display(Path root, Path module) {
        return root.relativize(module).toString().replace('\\', '/');
    }

    /** Parses one file; {@code root} is the directory it lives in. */
    public static Workspace parse(Path root, Path file) {
        String text;
        try {
            text = Files.readString(file);
        } catch (IOException e) {
            throw new WorkspaceException("cannot read " + file + " — " + e.getMessage());
        }
        Map<String, Object> document;
        try {
            document = TomlUtils.parse(text);
        } catch (RuntimeException e) {
            throw new WorkspaceException(at(file, null) + e.getMessage());
        }
        SchemaSource source = SchemaSource.scan(text);

        for (String section : document.keySet()) {
            if (!section.equals("ws")) {
                throw new WorkspaceException(at(file, source.section(section))
                        + "unknown section [" + section + "] — a workspace file holds [ws] only");
            }
        }
        Object section = document.get("ws");
        if (!(section instanceof Map<?, ?> table)) {
            throw new WorkspaceException(at(file, null) + "[ws] is required");
        }
        for (Object key : table.keySet()) {
            if (!key.equals("modules")) {
                throw new WorkspaceException(at(file, source.key("ws", String.valueOf(key)))
                        + "[ws]." + key + " is not a key — allowed: modules");
            }
        }
        SchemaSource.Site modulesSite = source.key("ws", "modules");
        Object listed = table.get("modules");
        if (!(listed instanceof List<?> entries)) {
            throw new WorkspaceException(at(file, modulesSite)
                    + "[ws].modules must be an array of paths");
        }

        Path rootReal;
        try {
            rootReal = root.toRealPath();
        } catch (IOException e) {
            throw new WorkspaceException("the workspace root " + root + " is not a directory");
        }
        if (Files.isRegularFile(root.resolve("jeno.toml"))) {
            throw new WorkspaceException("the workspace root " + root
                    + " is also a module (it has jeno.toml) — a directory cannot be both");
        }

        Set<Path> seen = new LinkedHashSet<>();
        List<Path> modules = new ArrayList<>();
        List<String> declared = new ArrayList<>();
        for (Object entry : entries) {
            if (!(entry instanceof String modulePath) || modulePath.isBlank()) {
                throw new WorkspaceException(at(file, modulesSite)
                        + "[ws].modules entries must be non-blank strings");
            }
            declared.add(modulePath);
            Path module = root.resolve(modulePath).normalize();
            if (!Files.isDirectory(module)) {
                throw new WorkspaceException(at(file, modulesSite)
                        + "module '" + modulePath + "' does not exist under " + root);
            }
            if (!Files.isRegularFile(module.resolve("jeno.toml"))) {
                if (Files.isRegularFile(module.resolve(LegacyNames.MANIFEST))) {
                    throw new LegacyNames.LegacyException(LegacyNames.manifest(module));
                }
                throw new WorkspaceException(at(file, modulesSite)
                        + "module '" + modulePath + "' has no jeno.toml");
            }
            Path real;
            try {
                real = module.toRealPath();
            } catch (IOException e) {
                throw new WorkspaceException(at(file, modulesSite)
                        + "module '" + modulePath + "' cannot be resolved");
            }
            if (!seen.add(real)) {
                throw new WorkspaceException(at(file, modulesSite)
                        + "modules " + declared + " name the same directory twice (" + real + ")");
            }
            modules.add(real);
        }

        // Two modules claiming one id make every replacement and every root
        // orchestration ambiguous, so the file is rejected the moment it is read
        // — not only when a classpath happens to ask about that id.
        Map<String, Path> byId = new java.util.LinkedHashMap<>();
        for (Path module : modules) {
            String id = moduleId(readProject(rootReal, module));
            Path previous = byId.putIfAbsent(id, module);
            if (previous != null) {
                throw new WorkspaceException(at(file, modulesSite) + "two modules claim '"
                        + id + "': " + display(rootReal, previous) + " and "
                        + display(rootReal, module));
            }
        }
        return new Workspace(rootReal, file, List.copyOf(modules));
    }

    /** A workspace file that cannot be read or does not make sense. */
    public static class WorkspaceException extends RuntimeException {
    @java.io.Serial
    private static final long serialVersionUID = 1L;
        WorkspaceException(String message) {
            super(message);
        }
    }

    /** A {@code --module} argument the user has to fix — a usage error, not a file error. */
    public static final class UsageException extends WorkspaceException {
    @java.io.Serial
    private static final long serialVersionUID = 1L;
        UsageException(String message) {
            super(message);
        }
    }
}
