package com.jujin.mj.resolve;

/**
 * mj.lock as text (SPEC.md §4): one {@code [[artifacts]]} row per artifact,
 * sorted by id, each pinned by its own sha256 and its metadata's sha256 —
 * release assets are mutable, so the bytes live in the lockfile, not the
 * URL. The digests come from a {@link DigestSource}; M3's download client
 * computes them from the fetched bytes, tests stub them.
 */
public final class LockFile {

    private LockFile() {}

    public static String serialize(ResolvedGraph graph, DigestSource digests) {
        StringBuilder out = new StringBuilder();
        out.append("# generated by mj — commit to version control, do not edit by hand\n");
        for (ResolvedGraph.ResolvedArtifact artifact : graph.artifacts()) {
            out.append("[[artifacts]]\n");
            out.append("id = ").append(string(artifact.id())).append('\n');
            out.append("version = ").append(string(artifact.version())).append('\n');
            out.append("source = ").append(string(artifact.source())).append('\n');
            out.append("url = ").append(string(artifact.jarUrl())).append('\n');
            out.append("sha256 = ").append(string(digests.sha256(artifact.jarUrl()))).append('\n');
            if (artifact.metadataUrl() != null) {
                out.append("meta-sha256 = ")
                        .append(string(digests.sha256(artifact.metadataUrl()))).append('\n');
            }
            out.append("depth = ").append(artifact.depth()).append('\n');
        }
        return out.toString();
    }

    /** Escapes a TOML basic string — ids, versions and URLs never carry
     *  control characters, but a quote or backslash in a URL must survive. */
    private static String string(String value) {
        StringBuilder out = new StringBuilder("\"");
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '"' -> out.append("\\\"");
                case '\\' -> out.append("\\\\");
                default -> out.append(c);
            }
        }
        return out.append('"').toString();
    }
}
