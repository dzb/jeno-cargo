package com.jujin.mj.cli;

import com.jujin.freeway.ioc.annotation.Inject;
import com.jujin.mj.project.MjProject;
import com.jujin.mj.project.ProjectReader;
import com.jujin.mj.store.ArtifactStore;
import com.jujin.mj.store.LockFileReader;
import com.jujin.mj.store.LockedArtifact;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

/**
 * {@code mj package self}: assembles mj's own distribution directory and
 * packages it as a self-installing tar.gz — the shape maven and gradle ship
 * in, generated by mj from its own lockfile:
 *
 * <pre>
 *   target/mj-0.1.0/
 *   ├── install.sh             self-installing script (copies to $HOME/.mj/)
 *   ├── bin/mj                 POSIX launcher
 *   ├── lib/
 *   │   ├── mj.jar             the tool itself
 *   │   ├── &lt;runtime closure&gt;
 *   │   └── toolchain/junit/   the lifecycle toolchain, shipped offline
 *   └── SHA256SUMS
 * </pre>
 *
 * <p>Plus a tar.gz of the whole directory — the release artifact that
 * {@code setup.sh} downloads and installs. The one-liner is:
 *
 * <pre>
 *   curl -fsSL https://raw.githubusercontent.com/dzb/mj-cargo/main/setup.sh | bash
 * </pre>
 */
public final class SelfPackageCommand implements Command {

    private static final String CLASSES = "target/classes";

    private static final String LAUNCHER = """
        #!/bin/sh
        # mj — modern java manager

        PRG="$0"
        while [ -h "$PRG" ]; do
            link=$(ls -ld "$PRG" | sed -e 's/^.* -> //')
            if [ -n "$link" ]; then
                case "$link" in /*) PRG="$link" ;; *) PRG="$(dirname "$PRG")/$link" ;; esac
            fi
            PRG=$(dirname "$PRG")
        done
        MJ_HOME=$(cd "$(dirname "$PRG")/.." && pwd)

        if [ -n "$JAVA_HOME" ]; then
            JAVA="$JAVA_HOME/bin/java"
        else
            JAVA=$(command -v java 2>/dev/null)
        fi
        if [ -z "$JAVA" ]; then
            echo "mj: no java found — set JAVA_HOME or add java to PATH" >&2
            exit 1
        fi

        TOOLCHAIN_CP=""
        if [ -d "$MJ_HOME/lib/toolchain" ]; then
            for jar_dir in "$MJ_HOME/lib/toolchain"/*/; do
                for jar_file in "$jar_dir"*.jar; do
                    if [ -f "$jar_file" ]; then
                        TOOLCHAIN_CP="$TOOLCHAIN_CP:$jar_file"
                    fi
                done
            done
        fi

        exec "$JAVA" -cp "$MJ_HOME/lib/mj.jar:$MJ_HOME/lib/*:$TOOLCHAIN_CP" com.jujin.mj.cli.Mj "$@"
        """;

    private static boolean isToolchain(LockedArtifact artifact) {
        return artifact.id().startsWith("org.junit.")
                || artifact.id().equals("org.opentest4j:opentest4j");
    }

    private static String originalName(LockedArtifact artifact) {
        String url = artifact.url();
        String name = url.substring(url.lastIndexOf('/') + 1);
        if (name.isBlank() || !name.contains(".")) {
            return artifact.sha256().substring(0, 12) + ".jar";
        }
        return name;
    }

    private final ArtifactStore store;
    private final Path projectDir;

    public SelfPackageCommand(ArtifactStore store, Path projectDir) {
        this.store = store;
        this.projectDir = projectDir;
    }

    @Override
    public String name() {
        return "selfpackage";
    }

    @Override
    public String summary() {
        return "assemble mj's distribution directory + install.sh + tar.gz";
    }

    @Override
    public int execute(List<String> args) {
        if (!Files.exists(projectDir.resolve("mj.lock"))) {
            System.err.println("mj: no mj.lock in " + projectDir + " — run mj lock first");
            return 1;
        }
        if (!Files.isDirectory(projectDir.resolve(CLASSES))) {
            System.err.println("mj: " + CLASSES + " is missing — run mj build first");
            return 1;
        }
        MjProject project;
        List<LockedArtifact> locked;
        int toolchainJars = 0;
        Map<String, Path> jars;
        try {
            project = ProjectReader.parse(Files.readString(projectDir.resolve("mj.toml")));
            locked = LockFileReader.read(Files.readString(projectDir.resolve("mj.lock")));
            jars = store.verifiedJars(locked);
        } catch (IOException | RuntimeException e) {
            System.err.println("mj: " + e.getMessage());
            return 1;
        }

        String version = project.version();
        Path dist = projectDir.resolve("target/mj-" + version);
        Path lib = dist.resolve("lib");
        Path toolchain = lib.resolve("toolchain/junit");
        Path bin = dist.resolve("bin");
        try {
            Files.createDirectories(bin);
            Files.createDirectories(toolchain);
        } catch (IOException e) {
            System.err.println("mj: cannot create " + dist);
            return 1;
        }

        try {
            // the tool itself
            Process jarTool = new ProcessBuilder("jar", "--create", "--file",
                    lib.resolve("mj.jar").toString(), "--no-manifest",
                    "-C", projectDir.resolve(CLASSES).toString(), ".")
                    .inheritIO().start();
            if (jarTool.waitFor() != 0) {
                System.err.println("mj: cannot jar the build output");
                return 1;
            }

            // the runtime closure and the toolchain
            for (LockedArtifact artifact : locked) {
                Path jar = jars.get(artifact.id());
                String fileName = originalName(artifact);
                Path target = isToolchain(artifact)
                        ? toolchain.resolve(fileName)
                        : lib.resolve(fileName);
                Files.copy(jar, target, StandardCopyOption.REPLACE_EXISTING);
                if (isToolchain(artifact)) {
                    toolchainJars++;
                }
            }

            // the launcher
            Path launcher = bin.resolve("mj");
            Files.writeString(launcher, LAUNCHER, StandardCharsets.UTF_8);
            Files.setPosixFilePermissions(launcher,
                    PosixFilePermissions.fromString("r-xr-xr-x"));

            // the installer — travels in the tar.gz, self-installs to $HOME/.mj/
            Files.writeString(dist.resolve("setup.sh"), installScript(version),
                    StandardCharsets.UTF_8);
            Files.setPosixFilePermissions(dist.resolve("setup.sh"),
                    PosixFilePermissions.fromString("r-xr-xr-x"));

            // the integrity manifest
            StringBuilder sums = new StringBuilder();
            try (Stream<Path> stream = Files.walk(dist)) {
                for (Path file : stream.filter(Files::isRegularFile)
                        .filter(path -> !path.getFileName().toString().equals("SHA256SUMS"))
                        .sorted()
                        .toList()) {
                    String relative = dist.relativize(file).toString().replace('\\', '/');
                    sums.append(ArtifactStore.sha256(file)).append("  ")
                            .append(relative).append('\n');
                }
            }
            Files.writeString(dist.resolve("SHA256SUMS"), sums.toString());
        } catch (IOException | InterruptedException e) {
            System.err.println("mj: cannot assemble the distribution: " + e.getMessage());
            return 1;
        }

        // tar.gz — the release artifact
        Path tarGz = projectDir.resolve("target/mj-bin-" + version + ".tar.gz");
        try {
            Process tar = new ProcessBuilder("tar", "-czf", tarGz.toString(),
                    "-C", dist.getParent().toString(), "mj-" + version)
                    .inheritIO().start();
            if (tar.waitFor() != 0) {
                System.err.println("mj: tar.gz creation failed");
                return 1;
            }
        } catch (IOException | InterruptedException e) {
            System.err.println("mj: tar.gz creation failed");
            return 1;
        }

        System.out.println("selfpackaged " + dist);
        System.out.println("  " + bin.resolve("mj") + " — the launcher");
        System.out.println("  " + lib + " — mj + runtime closure ("
                + (locked.size() - toolchainJars) + " jars)");
        System.out.println("  " + toolchain + " — the test lifecycle toolchain ("
                + toolchainJars + " jars)");
        System.out.println("  " + dist.resolve("SHA256SUMS"));
        System.out.println("  " + tarGz + " — the release artifact");
        System.out.println("\nupload the tar.gz to GitHub/Gitee releases, then users install with:");
        System.out.println("  curl -fsSL <setup.sh url> | bash");
        return 0;
    }

    /**
     * The self-installing script that travels in the tar.gz. After extraction,
     * it copies the distribution to {@code $HOME/.mj/} and configures PATH.
     */
    private static String installScript(String version) {
        return """
            #!/bin/bash
            # mj installer — version %s
            # Runs from the extracted tar.gz directory; installs to $HOME/.mj/

            set -e

            MJ_VERSION="%s"

            # Check Java 25+
            JAVA_MAJOR=$(java -version 2>&1 | head -1 | sed 's/.*"\\([0-9]*\\)\\..*/\\1/')
            if [ -z "$JAVA_MAJOR" ] || [ "$JAVA_MAJOR" -lt 25 ]; then
                echo "mj requires JDK 25+ (found: ${JAVA_MAJOR:-none})"
                echo "  download: https://adoptium.net/temurin/releases/?version=25"
                exit 1
            fi

            # Install to $HOME/.mj/ — MJ_HOME matches the launcher's derivation
            SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
            BIN_DIR="$HOME/.mj/bin"

            echo "installing mj $MJ_VERSION to $HOME/.mj/ ..."
            mkdir -p "$BIN_DIR"
            rm -rf "$HOME/.mj/lib"
            cp -R "$SCRIPT_DIR"/lib "$HOME/.mj/"

            # Generate the launcher (MJ_HOME points at the install dir)
            cat > "$BIN_DIR/mj" << 'LAUNCHER_EOF'
            #!/bin/sh
            # mj — modern java manager (installed by mj installer)

            PRG="$0"
            while [ -h "$PRG" ]; do
                link=$(ls -ld "$PRG" | sed -e 's/^.* -> //')
                if [ -n "$link" ]; then
                    case "$link" in /*) PRG="$link" ;; *) PRG="$(dirname "$PRG")/$link" ;; esac
                fi
                PRG=$(dirname "$PRG")
            done
            MJ_HOME=$(cd "$(dirname "$PRG")/.." && pwd)

            if [ -n "$JAVA_HOME" ]; then
                JAVA="$JAVA_HOME/bin/java"
            else
                JAVA=$(command -v java 2>/dev/null)
            fi
            if [ -z "$JAVA" ]; then
                echo "mj: no java found — set JAVA_HOME or add java to PATH" >&2
                exit 1
            fi

            TOOLCHAIN_CP=""
            if [ -d "$MJ_HOME/lib/toolchain" ]; then
                for jar_dir in "$MJ_HOME/lib/toolchain"/*/; do
                    for jar_file in "$jar_dir"*.jar; do
                        if [ -f "$jar_file" ]; then
                            TOOLCHAIN_CP="$TOOLCHAIN_CP:$jar_file"
                        fi
                    done
                done
            fi

            exec "$JAVA" -cp "$MJ_HOME/lib/mj.jar:$MJ_HOME/lib/*:$TOOLCHAIN_CP" com.jujin.mj.cli.Mj "$@"
            LAUNCHER_EOF
            chmod +x "$BIN_DIR/mj"

            # PATH — auto-detect shell and append to the right config file
            USER_SHELL=$(basename "${SHELL:-/bin/bash}")
            case "$USER_SHELL" in
                zsh)  CONFIG_FILES="$HOME/.zshrc" ;;
                fish) CONFIG_FILES="$HOME/.config/fish/config.fish" ;;
                *)    CONFIG_FILES="$HOME/.bashrc $HOME/.profile" ;;
            esac
            for CONFIG_FILE in $CONFIG_FILES; do
                if [ -f "$CONFIG_FILE" ] && grep -qF '.mj/bin' "$CONFIG_FILE" 2>/dev/null; then
                    continue  # already configured
                fi
                echo 'export PATH="$PATH:$HOME/.mj/bin"' >> "$CONFIG_FILE"
                echo "  PATH updated in $CONFIG_FILE"
            done

            # Symlink to /usr/local/bin (best-effort, optional)
            if [ ! -e "/usr/local/bin/mj" ] && [ -w "/usr/local/bin" ] 2>/dev/null; then
                ln -sf "$BIN_DIR/mj" /usr/local/bin/mj 2>/dev/null || true
            elif command -v sudo >/dev/null 2>&1; then
                sudo ln -sf "$BIN_DIR/mj" /usr/local/bin/mj 2>/dev/null || true
            fi

            echo ""
            echo "mj $MJ_VERSION installed — run 'mj' to verify"
            """.formatted(version, version);
    }
}
