package com.jujin.mjm.cli;

import com.jujin.mjm.store.ArtifactStore;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** Unknown arguments are usage errors; `--` ends mjm's options. */
class StrictArgumentsTest {

    @TempDir
    Path dir;

    private ArtifactStore store;
    private Path project;

    @BeforeEach
    void setUp() throws Exception {
        ProjectLock.useRoot(dir.resolve(".locks"));
        com.jujin.mjm.store.Paths.useForTesting(dir.resolve(".cache/store"),
                dir.resolve(".cache/sources"), dir.resolve(".locks"));
        com.jujin.mjm.resolve.ArtifactLocations.useProjectRoot(dir);
        store = new ArtifactStore(dir.resolve(".cache/store"));
        project = dir.resolve("proj");
        Files.createDirectories(project.resolve("src/main/java/app"));
        Files.writeString(project.resolve("mjm.toml"), """
            [project]
            name = "proj"
            version = "0.1.0"
            main = "app.Main"
            """);
        Files.writeString(project.resolve("mjm.lock"),
                "# generated by mjm — commit to version control, do not edit by hand\n");
        Files.writeString(project.resolve("src/main/java/app/Main.java"), """
            package app;

            public final class Main {
                public static void main(String[] args) throws Exception {
                    java.nio.file.Files.writeString(
                            java.nio.file.Path.of("args.txt"), String.join("|", args));
                }
            }
            """);
        assertEquals(0, new BuildCommand(store, project).execute(List.of()));
        resetOffline();
    }

    @AfterEach
    void tearDown() {
        resetOffline();
        ProjectLock.useUserRoot();
        com.jujin.mjm.store.Paths.resetForTesting();
        com.jujin.mjm.resolve.ArtifactLocations.useProjectRoot(Path.of("").toAbsolutePath());
    }

    @Test
    void buildTestBundleAndUpdateRejectUnknownArguments() {
        assertEquals(2, new BuildCommand(store, project).execute(List.of("--bogus")));
        assertFalse(Files.exists(project.resolve("target/dist")), "build did not package");

        assertEquals(2, new TestCommand(store, project).execute(List.of("--bogus")));
        assertEquals(2, new BundleCommand(store, project).execute(List.of("--bogus")));
        assertFalse(Files.exists(project.resolve("target/dist")), "bundle did nothing");

        assertEquals(2, new UpdateCommand().execute(List.of("--bogus")),
                "update checks its arguments before the network");
    }

    @Test
    void whyAndPublishRejectExtraArguments() {
        assertEquals(2, new WhyCommand(store, null, null, project)
                .execute(List.of("app:main", "extra")));

        assertEquals(2, new PublishCommand(project).execute(List.of("https://host/", "junk")));
    }

    @Test
    void aModuleFlagOutsideAWorkspaceIsAUsageError() throws IOException {
        deleteTree(project.resolve("target/classes"));
        Result result = run(new CommandRunner(List.of(new BuildCommand(store, project))),
                "build", "--module", "x");

        assertEquals(2, result.exit());
        assertTrue(result.err().contains("--module is only used at a workspace root"),
                result.err());
        assertFalse(Files.exists(project.resolve("target/classes/app/Main.class")),
                "nothing was compiled");
    }

    // ------------------------------------------------------------------

    private static Result run(CommandRunner runner, String... args) {
        PrintStream originalOut = System.out;
        PrintStream originalErr = System.err;
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        int exit;
        try {
            System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
            System.setErr(new PrintStream(err, true, StandardCharsets.UTF_8));
            exit = runner.run(args);
        } finally {
            System.setOut(originalOut);
            System.setErr(originalErr);
        }
        return new Result(exit, out.toString(StandardCharsets.UTF_8),
                err.toString(StandardCharsets.UTF_8));
    }

    private static void deleteTree(Path root) throws IOException {
        if (!Files.exists(root)) {
            return;
        }
        try (var walk = Files.walk(root)) {
            for (Path path : walk.sorted(java.util.Comparator.reverseOrder()).toList()) {
                Files.deleteIfExists(path);
            }
        }
    }

    private static void resetOffline() {
        try {
            var field = ArtifactStore.class.getDeclaredField("offline");
            field.setAccessible(true);
            field.set(null, false);
        } catch (ReflectiveOperationException e) {
            throw new AssertionError("cannot reset the offline flag", e);
        }
    }

    private record Result(int exit, String out, String err) {}
}
