package com.jujin.mjm.cli;

import com.jujin.mjm.store.ArtifactStore;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** At a workspace root, commands that act on one project demand --module. */
class WorkspaceRootModuleTest {

    @TempDir
    Path root;

    private Path module;

    @BeforeEach
    void setUp() throws Exception {
        ProjectLock.useRoot(root.resolve(".locks"));
        com.jujin.mjm.store.Paths.useForTesting(root.resolve(".cache/store"),
                root.resolve(".cache/sources"), root.resolve(".locks"));
        com.jujin.mjm.resolve.ArtifactLocations.useProjectRoot(root);
        module = root.resolve("libs/core");
        Files.createDirectories(module);
        Files.writeString(module.resolve("mjm.toml"), """
            [project]
            name = "core"
            version = "0.1.0"
            """);
        Files.writeString(module.resolve("mjm.lock"),
                "# generated by mjm — commit to version control, do not edit by hand\n");
        Files.writeString(root.resolve("mjm.ws.toml"), """
            [ws]
            modules = ["libs/core"]
            """);
    }

    @AfterEach
    void tearDown() {
        ProjectLock.useUserRoot();
        com.jujin.mjm.store.Paths.resetForTesting();
        com.jujin.mjm.resolve.ArtifactLocations.useProjectRoot(Path.of("").toAbsolutePath());
    }

    @Test
    void auditNeedsAModuleAtTheRoot() {
        Result bare = run(new AuditCommand(root));
        assertEquals(2, bare.exit());
        assertTrue(bare.err().contains("this directory is a workspace root — say which module:"),
                bare.err());

        Result selected = run(new AuditCommand(root), "--module", "libs/core");
        assertEquals(0, selected.exit(), selected.out() + selected.err());
    }

    @Test
    void outdatedNeedsAModuleAtTheRoot() {
        Result bare = run(new OutdatedCommand(root));
        assertEquals(2, bare.exit());
        assertTrue(bare.err().contains("this directory is a workspace root — say which module:"),
                bare.err());

        Result selected = run(new OutdatedCommand(root), "--module", "libs/core");
        assertEquals(0, selected.exit(), selected.out() + selected.err());
    }

    @Test
    void publishNeedsAModuleAtTheRoot() {
        Result bare = run(new PublishCommand(root));
        assertEquals(2, bare.exit());
        assertTrue(bare.err().contains("this directory is a workspace root — say which module:"),
                bare.err());

        Result selected = run(new PublishCommand(root), "--module", "libs/core");
        assertEquals(1, selected.exit(), "it reached the module and asked for a build");
        assertTrue(selected.err().contains("target/classes is missing"), selected.err());
    }

    @Test
    void moduleOutsideAWorkspaceIsAUsageError() {
        Result result = run(new AuditCommand(module), "--module", "libs/core");

        assertEquals(2, result.exit());
        assertTrue(result.err().contains("--module is only used at a workspace root"),
                result.err());
    }

    // ------------------------------------------------------------------

    private static Result run(Command command, String... args) {
        PrintStream originalOut = System.out;
        PrintStream originalErr = System.err;
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        int exit;
        try {
            System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
            System.setErr(new PrintStream(err, true, StandardCharsets.UTF_8));
            exit = command.execute(List.of(args));
        } finally {
            System.setOut(originalOut);
            System.setErr(originalErr);
        }
        return new Result(exit, out.toString(StandardCharsets.UTF_8),
                err.toString(StandardCharsets.UTF_8));
    }

    private record Result(int exit, String out, String err) {}
}
