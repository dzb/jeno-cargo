package com.jujin.mjm.cli;

import com.jujin.mjm.store.ArtifactStore;
import com.jujin.freeway.commons.json.JsonObject;
import com.jujin.freeway.commons.json.JsonUtils;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;

/** A usage error keeps exit 2 and reports the stable USAGE code in JSON. */
class JsonUsageCodeTest {

    @TempDir
    Path dir;

    private ArtifactStore store;
    private Path project;

    @BeforeEach
    void setUp() throws Exception {
        ProjectLock.useRoot(dir.resolve(".locks"));
        store = new ArtifactStore(dir.resolve("store"));
        project = Files.createDirectories(dir.resolve("project"));
        Files.writeString(project.resolve("mjm.toml"), """
                [project]
                name = "demo"
                version = "0.1.0"
                """);
        Files.writeString(project.resolve("mjm.lock"),
                "# generated by mjm — commit to version control, do not edit by hand\n");
    }

    @AfterEach
    void tearDown() {
        ProjectLock.useUserRoot();
    }

    @Test
    void buildUnknownArgumentIsUsage() {
        assertUsage(new BuildCommand(store, project));
    }

    @Test
    void packageBundleCleanAndTestUnknownArgumentsAreUsage() {
        assertUsage(new PackageCommand(store, project));
        assertUsage(new BundleCommand(store, project));
        assertUsage(new CleanCommand(project));
        assertUsage(new TestCommand(store, project));
    }

    private static void assertUsage(Command command) {
        PrintStream originalOut = System.out;
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        int exit;
        try {
            System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
            exit = command.execute(List.of("--json", "--bogus"));
        } finally {
            System.setOut(originalOut);
        }
        assertEquals(2, exit, out.toString(StandardCharsets.UTF_8));
        JsonObject root = JsonUtils.parseObject(out.toString(StandardCharsets.UTF_8).strip());
        assertEquals("error", root.getString("status"));
        assertEquals("USAGE", root.getArray("diagnostics").getObject(0).getString("code"));
    }
}
