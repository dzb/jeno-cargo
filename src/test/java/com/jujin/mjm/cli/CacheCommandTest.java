package com.jujin.mjm.cli;

import com.jujin.mjm.store.Paths;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** {@code mjm cache}: the three roots, their sizes, and the two reclaim verbs. */
class CacheCommandTest {

    @TempDir
    Path dir;

    private Path store;
    private Path sources;
    private Path locks;

    @BeforeEach
    void pointPathsAtScratch() {
        store = dir.resolve("store");
        sources = dir.resolve("sources");
        locks = dir.resolve("locks");
        Paths.useForTesting(store, sources, locks);
    }

    @AfterEach
    void restorePaths() {
        Paths.resetForTesting();
    }

    @Test
    void dirNamesTheThreeRoots() throws Exception {
        String out = run("dir");

        assertTrue(out.contains("store   " + store), out);
        assertTrue(out.contains("sources " + sources), out);
        assertTrue(out.contains("locks   " + locks), out);
    }

    @Test
    void sizeReportsEachRootAndTheTotal() throws Exception {
        Files.createDirectories(store);
        Files.write(store.resolve("a.jar"), new byte[2048]);
        Files.createDirectories(sources);
        Files.write(sources.resolve("b.txt"), new byte[1024]);

        String out = run("size");

        assertTrue(out.contains("store   2.0 KiB"), out);
        assertTrue(out.contains("sources 1.0 KiB"), out);
        assertTrue(out.contains("total   3.0 KiB"), out);
    }

    @Test
    void pruneRemovesOnlyTheLocksWhoseProjectIsGone() throws Exception {
        Files.createDirectories(locks);
        Path live = Files.createDirectories(dir.resolve("live-project"));
        Path gone = dir.resolve("gone-project");
        Files.writeString(locks.resolve("live.lock"), "project=" + live + "\n");
        Files.writeString(locks.resolve("gone.lock"), "project=" + gone + "\n");
        Files.writeString(locks.resolve("old.lock"), "");  // pre-sidecar: unknown

        assertEquals(0, command().execute(List.of("prune")));

        assertTrue(Files.exists(locks.resolve("live.lock")), "a live project keeps its lock");
        assertFalse(Files.exists(locks.resolve("gone.lock")), "a dead project's lock goes");
        assertTrue(Files.exists(locks.resolve("old.lock")), "an unknown lock is not 'dead'");
    }

    @Test
    void pruneRemovesInterruptedDownloadsAndDanglingIndexEntries() throws Exception {
        Files.createDirectories(store.resolve("index"));
        Files.createDirectories(store);
        Files.write(store.resolve("part-123.tmp"), new byte[10]);
        String keptDigest = "a".repeat(64);
        String danglingDigest = "b".repeat(64);
        Files.write(store.resolve(keptDigest + ".jar"), new byte[4]);
        Files.writeString(store.resolve("index/kept.url"), keptDigest + "\n");
        Files.writeString(store.resolve("index/dangling.url"), danglingDigest + "\n");

        assertEquals(0, command().execute(List.of("prune")));

        assertFalse(Files.exists(store.resolve("part-123.tmp")), "the interrupted download goes");
        assertFalse(Files.exists(store.resolve("index/dangling.url")),
                "the index entry with no artifact goes");
        assertTrue(Files.exists(store.resolve("index/kept.url")),
                "an index entry that still has its artifact stays");
    }

    @Test
    void purgeRemovesStoreAndSourcesAndLeavesTheProjectAlone() throws Exception {
        Files.createDirectories(store);
        Files.write(store.resolve("a.jar"), new byte[4096]);
        Files.createDirectories(sources);
        Files.write(sources.resolve("tree.tar.gz"), new byte[2048]);
        Files.createDirectories(locks);
        Path project = Files.createDirectories(dir.resolve("project"));
        Files.writeString(project.resolve("mjm.lock"), "# generated by mjm\n");
        byte[] lockBefore = Files.readAllBytes(project.resolve("mjm.lock"));

        String out = run("purge", "--yes");

        assertFalse(Files.exists(store), "the store is gone");
        assertFalse(Files.exists(sources), "and the sources");
        assertTrue(out.contains("freed 4.0 KiB from " + store),
                "the store's release is reported: " + out);
        assertTrue(out.contains("freed 2.0 KiB from " + sources),
                "and the sources': " + out);
        assertTrue(Files.exists(project.resolve("mjm.lock")), "the project's lock stays");
        assertEquals(new String(lockBefore, StandardCharsets.UTF_8),
                Files.readString(project.resolve("mjm.lock")));
        assertTrue(Files.exists(locks), "the locks root is not clean's business");
    }

    private CacheCommand command() {
        return new CacheCommand();
    }

    private String run(String... args) throws IOException {
        Result result = execute(args);
        assertEquals(0, result.exit(), result.out());
        return result.out();
    }

    private Result execute(String... args) {
        PrintStream originalOut = System.out;
        PrintStream originalErr = System.err;
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        int exit;
        try {
            System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
            System.setErr(new PrintStream(err, true, StandardCharsets.UTF_8));
            exit = command().execute(List.of(args));
        } finally {
            System.setOut(originalOut);
            System.setErr(originalErr);
        }
        return new Result(exit, out.toString(StandardCharsets.UTF_8),
                err.toString(StandardCharsets.UTF_8));
    }

    private record Result(int exit, String out, String err) {}

    @Test
    void cleanIsStillAnAliasForPurge() throws Exception {
        Files.createDirectories(store);
        Files.writeString(store.resolve("x.jar"), "bytes");

        run("clean", "--yes");

        assertFalse(Files.exists(store), "the alias runs the same purge");
        assertTrue(command().usage().contains("purge"), command().usage());
        assertFalse(command().usage().contains("clean"), "clean is the alias, not the verb");
    }

    @Test
    void purgeRefusesWithoutYes() throws Exception {
        Files.createDirectories(store);
        Files.writeString(store.resolve("x.jar"), "bytes");
        Files.createDirectories(sources);

        Result result = execute("purge");

        assertEquals(2, result.exit());
        assertTrue(result.out().contains(store.toString()), result.out());
        assertTrue(result.out().contains("--yes"), result.out());
        assertTrue(Files.exists(store), "nothing is deleted without --yes");
        assertTrue(Files.exists(sources));

        Result alias = execute("clean");
        assertEquals(2, alias.exit(), "the alias has the same protection");
        assertTrue(Files.exists(store));
    }

    @Test
    void dryRunReportsWithoutDeleting() throws Exception {
        Files.createDirectories(store);
        Files.write(store.resolve("x.jar"), new byte[1024]);
        Files.createDirectories(sources);

        Result result = execute("purge", "--dry-run");

        assertEquals(0, result.exit());
        assertTrue(result.out().contains("would purge " + store), result.out());
        assertTrue(result.out().contains("1.0 KiB"), result.out());
        assertTrue(Files.exists(store), "--dry-run deletes nothing");
        assertTrue(Files.exists(sources));
    }

    @Test
    void purgeAndTheAliasRejectUnknownFlagsAndExtraArguments() throws Exception {
        assertEquals(2, execute("purge", "--force").exit());
        assertEquals(2, execute("purge", "extra").exit());
        assertEquals(2, execute("clean", "--dry-run", "extra").exit());
        assertEquals(2, execute("dir", "extra").exit());
    }
}
