package com.jujin.mjm.cli;

import com.jujin.mjm.resolve.ArtifactLocations;
import com.jujin.mjm.store.ArtifactStore;
import com.jujin.mjm.store.LockFileReader;
import com.jujin.mjm.store.LockedArtifact;
import com.jujin.mjm.store.StoreDescriptorSource;
import com.jujin.mjm.store.StorePomSource;
import com.sun.net.httpserver.HttpServer;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * A named {@code mjm:} repository: two-level layout, native descriptors, no
 * {@code [project].group} on either side.
 */
class MjmRepositoryTest {

    @TempDir
    Path dir;

    private HttpServer server;
    private final Map<String, byte[]> routes = new LinkedHashMap<>();
    private final List<String> puts = new ArrayList<>();

    @BeforeEach
    void isolateProjectLocks() {
        ProjectLock.useRoot(dir.resolve(".locks"));
    }

    @AfterEach
    void stopServer() {
        if (server != null) {
            server.stop(0);
        }
        ProjectLock.useUserRoot();
    }

    @Test
    void aNamedRepositoryResolvesDescriptorsAndTheirTransitives(@TempDir Path storeDir)
            throws Exception {
        serve("""
            [project]
            name = "widget"
            version = "1.0.0"

            [deps]
            "gadget" = "0.9.0"
            """.getBytes(), "/widget/1.0.0/widget-1.0.0.mjm.toml");
        serve("widget-jar".getBytes(), "/widget/1.0.0/widget-1.0.0.jar");
        serve("""
            [project]
            name = "gadget"
            version = "0.9.0"
            """.getBytes(), "/gadget/0.9.0/gadget-0.9.0.mjm.toml");
        serve("gadget-jar".getBytes(), "/gadget/0.9.0/gadget-0.9.0.jar");
        String base = start();

        Path project = Files.createDirectories(dir.resolve("project"));
        Files.writeString(project.resolve("mjm.toml"), """
            [project]
            name = "demo"
            version = "0.1.0"

            [repos]
            mine = "mjm:%s"

            [deps]
            "widget" = "mine:1.0.0"
            """.formatted(base));
        ArtifactStore store = new ArtifactStore(storeDir);
        LockService lockService = new LockService(store, new StorePomSource(store),
                new StoreDescriptorSource(store));

        lockService.refresh(project);

        List<LockedArtifact> locked = LockFileReader.read(
                Files.readString(project.resolve("mjm.lock")));
        assertEquals(2, locked.size(), "the descriptor's dependency joins the closure");
        LockedArtifact widget = locked.stream().filter(row -> row.id().equals("widget"))
                .findFirst().orElseThrow();
        assertEquals("mjm:" + base, widget.source(),
                "source keeps the declaration, like a local: repository");
        assertEquals(ArtifactLocations.mjmFile("mjm:" + base, "widget", "1.0.0", "jar"),
                widget.url());
        assertTrue(locked.stream().anyMatch(row -> row.id().equals("gadget")),
                "the sibling in the same repository is resolved");
    }

    @Test
    void publishToANamedRepositoryNeedsNoGroup(@TempDir Path storeDir) throws Exception {
        String base = start();  // accepts PUT, records the path
        Path project = Files.createDirectories(dir.resolve("publish"));
        Files.createDirectories(project.resolve("src/main/java/demo"));
        Files.writeString(project.resolve("src/main/java/demo/Main.java"), """
            package demo;

            public final class Main {
                public static void main(String[] args) {
                }
            }
            """);
        Files.writeString(project.resolve("mjm.toml"), """
            [project]
            name = "demo"
            version = "0.1.0"
            main = "demo.Main"
            """);
        Files.writeString(project.resolve("mjm.lock"), "# generated by mjm\n");
        ArtifactStore store = new ArtifactStore(storeDir);
        assertEquals(0, new BuildCommand(store, project).execute(List.of()));
        assertEquals(0, new PackageCommand(store, project).execute(List.of()));

        int exit = new PublishCommand(project).execute(List.of("mjm:" + base + "/repo/"));

        assertEquals(0, exit, "a group is not needed for the mjm: layout");
        assertEquals(List.of(
                "/repo/demo/0.1.0/demo-0.1.0.jar",
                "/repo/demo/0.1.0/demo-0.1.0.mjm.toml",
                "/repo/demo/0.1.0/demo-0.1.0.sha256"), puts);

        exit = new PublishCommand(project).execute(List.of(base + "/maven/"));
        assertEquals(1, exit, "the Maven layout still requires [project].group");
    }

    // ------------------------------------------------------------------

    private void serve(byte[] body, String path) {
        routes.put(path, body);
    }

    private String start() throws IOException {
        server = HttpServer.create(new InetSocketAddress("localhost", 0), 0);
        server.createContext("/", exchange -> {
            String path = exchange.getRequestURI().getPath();
            if (exchange.getRequestMethod().equals("PUT")) {
                exchange.getRequestBody().readAllBytes();
                puts.add(path);
                exchange.sendResponseHeaders(201, -1);
                exchange.close();
                return;
            }
            byte[] body = routes.get(path);
            if (body == null) {
                exchange.sendResponseHeaders(404, -1);
                exchange.close();
                return;
            }
            exchange.sendResponseHeaders(200, body.length);
            try (var out = exchange.getResponseBody()) {
                out.write(body);
            }
        });
        server.start();
        return "http://localhost:" + server.getAddress().getPort();
    }
}
