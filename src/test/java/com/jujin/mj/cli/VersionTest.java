package com.jujin.mj.cli;

import com.jujin.mj.store.ArtifactStore;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The version is declared once in mj.toml and derived everywhere else. The
 * build writes it as a resource ({@code META-INF/mj/version.properties}) and
 * as jar manifest entries; the resource is what survives all three layouts —
 * {@code target/classes}, a jar, and an installed dist — while the manifest
 * is the Java-conventional spelling that tools and IDEs read.
 */
class VersionTest {

    @TempDir
    Path dir;

    @Test
    void buildWritesTheVersionResourceFromMjToml(@TempDir Path storeDir) throws Exception {
        Files.createDirectories(dir.resolve("src/main/java/demo"));
        Files.writeString(dir.resolve("mj.toml"), """
            [project]
            name = "demo"
            version = "9.8.7"
            """);
        Files.writeString(dir.resolve("src/main/java/demo/App.java"),
                "package demo; public final class App {}");
        Files.writeString(dir.resolve("mj.lock"), "");

        assertEquals(0, new BuildCommand(new ArtifactStore(storeDir), dir).execute(List.of()));

        Path resource = dir.resolve("target/classes/META-INF/mj/version.properties");
        assertTrue(Files.exists(resource), "the build derives the version resource");
        assertTrue(Files.readString(resource).contains("version=9.8.7"),
                "the declared version lands in the resource");
    }

    @Test
    void theWrittenResourceRoundTripsThroughTheReaderFormat() {
        String text = Version.propertiesText("1.2.3");
        assertTrue(text.contains("version=1.2.3"), text);
        assertTrue(text.startsWith("# generated by mj"), "the file says it is generated");
    }

    @Test
    void distJarCarriesBothTheManifestAndTheResource(@TempDir Path storeDir) throws Exception {
        Files.createDirectories(dir.resolve("src/main/java/demo"));
        Files.writeString(dir.resolve("mj.toml"), """
            [project]
            name = "demo"
            version = "4.5.6"
            main = "demo.App"
            """);
        Files.writeString(dir.resolve("src/main/java/demo/App.java"), """
            package demo;

            public final class App {
                public static void main(String[] args) {
                    System.out.println("demo " + VersionProbe.version());
                }
            }
            """);
        // a tiny probe class that reads the same resource mj reads
        Files.writeString(dir.resolve("src/main/java/demo/VersionProbe.java"), """
            package demo;

            import java.io.InputStream;
            import java.util.Properties;

            final class VersionProbe {
                static String version() {
                    try (InputStream in = VersionProbe.class
                            .getResourceAsStream("/META-INF/mj/version.properties")) {
                        if (in == null) {
                            return "missing";
                        }
                        Properties p = new Properties();
                        p.load(in);
                        return p.getProperty("version");
                    } catch (Exception e) {
                        return "error";
                    }
                }
            }
            """);
        Files.writeString(dir.resolve("mj.lock"), "");

        ArtifactStore store = new ArtifactStore(storeDir);
        assertEquals(0, new BuildCommand(store, dir).execute(List.of()));
        assertEquals(0, new BundleCommand(store, dir).execute(List.of()));

        Path jar = dir.resolve("dist/demo-4.5.6/lib/demo-4.5.6.jar");
        assertTrue(Files.exists(jar), "the dist jar was written");
        try (var zip = new java.util.zip.ZipFile(jar.toFile())) {
            var manifestEntry = zip.getEntry("META-INF/MANIFEST.MF");
            assertTrue(manifestEntry != null, "the jar has a manifest");
            var manifest = new java.util.jar.Manifest(zip.getInputStream(manifestEntry));
            assertEquals("4.5.6", manifest.getMainAttributes()
                    .getValue("Implementation-Version"), "Java-conventional version entry");
            assertEquals("demo", manifest.getMainAttributes()
                    .getValue("Implementation-Title"));
            assertTrue(zip.getEntry("META-INF/mj/version.properties") != null,
                    "the resource travels inside the jar too");
        }
    }

    @Test
    void theRuntimeVersionComesFromTheGeneratedResource() {
        // mj test runs off target/classes, which the build stamped — so the
        // version is the declared one, not a scaffold and not "dev"
        assertFalse(Version.current().isBlank(), "a running mj always names itself");
        assertFalse(Version.UNKNOWN.equals(Version.current()),
                "the build wrote the resource, so there is nothing to guess");
        assertTrue(Version.current().matches("\\d+\\.\\d+\\.\\d+.*"),
                "a semver-shaped version, got " + Version.current());
    }
}
