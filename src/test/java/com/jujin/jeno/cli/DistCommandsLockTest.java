package com.jujin.jeno.cli;

import com.jujin.jeno.store.ArtifactStore;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicBoolean;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The commands that write {@code dist/} take the project lock, so a concurrent
 * {@code clean --dist} cannot delete a deliverable mid-write. Each test holds
 * the lock, starts the command, and proves it waits before touching the tree.
 */
class DistCommandsLockTest {

    @TempDir
    Path dir;

    @BeforeEach
    void isolateProjectLocks() {
        ProjectLock.useRoot(dir.resolve(".locks"));
    }

    @AfterEach
    void restoreProjectLocks() {
        ProjectLock.useUserRoot();
    }

    @Test
    void packageWaitsForTheProjectLock() throws Exception {
        buildableProject();

        assertEquals(0, new BuildCommand(new ArtifactStore(dir.resolve("store")), dir)
                .execute(List.of()));

        assertWaitsThenRuns(() -> new PackageCommand(new ArtifactStore(dir.resolve("store")), dir)
                .execute(List.of()));
        assertTrue(Files.isDirectory(dir.resolve("target/dist")), "the jar landed after the wait");
    }

    @Test
    void bundleWaitsForTheProjectLock() throws Exception {
        buildableProject();
        ArtifactStore store = new ArtifactStore(dir.resolve("store"));
        assertEquals(0, new BuildCommand(store, dir).execute(List.of()));

        assertWaitsThenRuns(() -> new BundleCommand(store, dir).execute(List.of()));
        assertTrue(Files.exists(dir.resolve("target/dist/demo-0.1.0.tar.gz")),
                "the archive landed whole after the wait");
    }

    @Test
    void releaseWaitsForTheProjectLock() throws Exception {
        buildableProject();
        ArtifactStore store = new ArtifactStore(dir.resolve("store"));
        assertEquals(0, new BuildCommand(store, dir).execute(List.of()));
        assertEquals(0, new BundleCommand(store, dir).execute(List.of()));

        assertWaitsThenRuns(() -> new ReleaseCommand(dir)
                .execute(List.of("--allow-unsigned")));
        assertTrue(Files.exists(dir.resolve("target/dist/release/install.sh")),
                "release prepared its files after the wait");
    }

    @Test
    void publishWaitsForTheProjectLock() throws Exception {
        buildableProject();
        ArtifactStore store = new ArtifactStore(dir.resolve("store"));
        assertEquals(0, new BuildCommand(store, dir).execute(List.of()));
        assertEquals(0, new PackageCommand(store, dir).execute(List.of()));

        // the upload is inside the lock too: the command does not even decide
        // what to upload until the lock is free
        assertWaitsThenRuns(() -> new PublishCommand(dir)
                .execute(List.of("http://127.0.0.1:9/repo/")));
    }

    private void buildableProject() throws IOException {
        Files.createDirectories(dir.resolve("src/main/java/demo"));
        Files.writeString(dir.resolve("src/main/java/demo/Main.java"), """
            package demo;

            public final class Main {
                public static void main(String[] args) {
                }
            }
            """);
        Files.writeString(dir.resolve("jeno.toml"), """
            [project]
            name = "demo"
            version = "0.1.0"
            main = "demo.Main"
            """);
        Files.writeString(dir.resolve("jeno.lock"), "# generated by jeno\n");
    }

    /** Holds the lock, starts {@code command}, and requires it to wait for release. */
    private void assertWaitsThenRuns(java.util.function.IntSupplier command) throws Exception {
        CountDownLatch held = new CountDownLatch(1);
        CountDownLatch release = new CountDownLatch(1);
        AtomicBoolean finished = new AtomicBoolean();

        Thread holder = new Thread(() -> ProjectLock.with(dir, () -> {
            held.countDown();
            try {
                release.await(20, TimeUnit.SECONDS);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            }
            return 0;
        }));
        holder.start();
        assertTrue(held.await(20, TimeUnit.SECONDS), "the lock is held");

        Thread writer = new Thread(() -> {
            command.getAsInt();
            finished.set(true);
        });
        writer.start();
        Thread.sleep(300);
        assertFalse(finished.get(), "the command waits for the lock instead of writing");

        release.countDown();
        writer.join(20_000);
        holder.join(20_000);
        assertTrue(finished.get(), "and proceeds once the lock is free");
    }
}
