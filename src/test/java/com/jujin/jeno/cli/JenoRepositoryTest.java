/**
 * A named {@code mjm:} repository: two-level layout, native descriptors, no
 * {@code [project].group} on either side.
 */
class JenoRepositoryTest {

    @TempDir
    Path dir;

    private HttpServer server;
    private final Map<String, byte[]> routes = new LinkedHashMap<>();
    private final List<String> puts = new ArrayList<>();

    @BeforeEach
    void isolateProjectLocks() {
        ProjectLock.useRoot(dir.resolve(".locks"));
    }

    @AfterEach
    void stopServer() {
        if (server != null) {
            server.stop(0);
        }
        ProjectLock.useUserRoot();
    }

    @Test
    void aNamedRepositoryResolvesDescriptorsAndTheirTransitives(@TempDir Path storeDir)
            throws Exception {
        serve("""
            [project]
            name = "widget"
            version = "1.0.0"

            [deps]
            "gadget" = "0.9.0"
            """.getBytes(), "/widget/1.0.0/widget-1.0.0.mjm.toml");
        serve("widget-jar".getBytes(), "/widget/1.0.0/widget-1.0.0.jar");
        serve("""
            [project]
            name = "gadget"
            version = "0.9.0"
            """.getBytes(), "/gadget/0.9.0/gadget-0.9.0.mjm.toml");
        serve("gadget-jar".getBytes(), "/gadget/0.9.0/gadget-0.9.0.jar");
        String base = start();

        Path project = Files.createDirectories(dir.resolve("project"));
        Files.writeString(project.resolve("mjm.toml"), """
            [project]
            name = "demo"
            version = "0.1.0"

            [repos]
            mine = "mjm:%s"

            [deps]
            "widget" = "mine:1.0.0"
            """.formatted(base));
        ArtifactStore store = new ArtifactStore(storeDir);
        LockService lockService = new LockService(store, new StorePomSource(store),
                new StoreDescriptorSource(store));

        lockService.refresh(project);

        List<LockedArtifact> locked = LockFileReader.read(
                Files.readString(project.resolve("mjm.lock")));
        assertEquals(2, locked.size(), "the descriptor's dependency joins the closure");
        LockedArtifact widget = locked.stream().filter(row -> row.id().equals("widget"))
                .findFirst().orElseThrow();
        assertEquals("mjm:" + base, widget.source(),
                "source keeps the declaration, like a local: repository");
        assertEquals(ArtifactLocations.mjmFile("mjm:" + base, "widget", "1.0.0", "jar"),
                widget.url());
        assertTrue(locked.stream().anyMatch(row -> row.id().equals("gadget")),
                "the sibling in the same repository is resolved");
    }

    @Test
    void publishToANamedRepositoryNeedsNoGroup(@TempDir Path storeDir) throws Exception {
        String base = start();  // accepts PUT, records the path
        Path project = Files.createDirectories(dir.resolve("publish"));
        Files.createDirectories(project.resolve("src/main/java/demo"));
        Files.writeString(project.resolve("src/main/java/demo/Main.java"), """
            package demo;

            public final class Main {
                public static void main(String[] args) {
                }
            }
            """);
        Files.writeString(project.resolve("mjm.toml"), """
            [project]
            name = "demo"
            version = "0.1.0"
            main = "demo.Main"
            """);
        Files.writeString(project.resolve("mjm.lock"), "# generated by mjm\n");
        ArtifactStore store = new ArtifactStore(storeDir);
        assertEquals(0, new BuildCommand(store, project).execute(List.of()));
        assertEquals(0, new PackageCommand(store, project).execute(List.of()));

        int exit = new PublishCommand(project).execute(List.of("mjm:" + base + "/repo/"));

        assertEquals(0, exit, "a group is not needed for the mjm: layout");
        assertEquals(List.of(
                "/repo/demo/0.1.0/demo-0.1.0.jar",
                "/repo/demo/0.1.0/demo-0.1.0.mjm.toml",
                "/repo/demo/0.1.0/demo-0.1.0.sha256"), puts);

        exit = new PublishCommand(project).execute(List.of(base + "/maven/"));
        assertEquals(1, exit, "a Maven-layout target is refused: mjm writes no POM");
    }

    @Test
    void publishingToTheSameRepositoryWritesSiblingsAsBareNames(@TempDir Path storeDir)
            throws Exception {
        serve("""
            [project]
            name = "gadget"
            version = "0.9.0"
            """.getBytes(), "/gadget/0.9.0/gadget-0.9.0.mjm.toml");
        serve(validJar(), "/gadget/0.9.0/gadget-0.9.0.jar");
        String base = start();

        Path project = siblingProject(base);
        ArtifactStore store = new ArtifactStore(storeDir);
        LockService lockService = new LockService(store, new StorePomSource(store),
                new StoreDescriptorSource(store));
        lockService.refresh(project);
        assertEquals(0, new BuildCommand(store, project).execute(List.of()));
        assertEquals(0, new PackageCommand(store, project).execute(List.of()));

        int exit = new PublishCommand(project).execute(List.of("mjm:" + base + "/"));

        assertEquals(0, exit);
        String descriptor = Files.readString(project.resolve("target/dist/demo-0.1.0.mjm.toml"));
        assertTrue(descriptor.contains("\"gadget\" = \"0.9.0\""),
                "a sibling is a fact: bare name and version, got:\n" + descriptor);
        assertTrue(!descriptor.contains("mine:"), descriptor);
    }

    @Test
    void publishingElsewhereRefusesTheSibling(@TempDir Path storeDir) throws Exception {
        serve("""
            [project]
            name = "gadget"
            version = "0.9.0"
            """.getBytes(), "/gadget/0.9.0/gadget-0.9.0.mjm.toml");
        serve(validJar(), "/gadget/0.9.0/gadget-0.9.0.jar");
        String base = start();

        Path project = siblingProject(base);
        ArtifactStore store = new ArtifactStore(storeDir);
        LockService lockService = new LockService(store, new StorePomSource(store),
                new StoreDescriptorSource(store));
        lockService.refresh(project);
        assertEquals(0, new BuildCommand(store, project).execute(List.of()));
        assertEquals(0, new PackageCommand(store, project).execute(List.of()));

        java.io.PrintStream original = System.err;
        var errors = new java.io.ByteArrayOutputStream();
        int exit;
        try {
            System.setErr(new java.io.PrintStream(errors, true, StandardCharsets.UTF_8));
            exit = new PublishCommand(project)
                    .execute(List.of("mjm:http://localhost:1/elsewhere/"));
        } finally {
            System.setErr(original);
        }

        String message = errors.toString(StandardCharsets.UTF_8);
        assertEquals(1, exit);
        assertTrue(message.contains("belongs to repository 'mine'"), message);
        assertTrue(message.contains("http://localhost:1/elsewhere/"),
                "the message names where you are publishing instead: " + message);
    }

    @Test
    void aGhTargetStillRefusesARepoBoundDependency(@TempDir Path storeDir) throws Exception {
        String base = start();
        Path project = siblingProject(base);
        Files.createDirectories(project.resolve("target/classes"));
        ArtifactStore store = new ArtifactStore(storeDir);
        // no lock/build needed: the dependency rule is checked before any upload

        java.io.PrintStream original = System.err;
        var errors = new java.io.ByteArrayOutputStream();
        int exit;
        try {
            System.setErr(new java.io.PrintStream(errors, true, StandardCharsets.UTF_8));
            exit = new PublishCommand(project).execute(List.of("gh:acme/demo"));
        } finally {
            System.setErr(original);
        }

        assertEquals(1, exit);
        assertTrue(errors.toString(StandardCharsets.UTF_8)
                .contains("belongs to repository 'mine'"));
    }

    private Path siblingProject(String base) throws IOException {
        Path project = Files.createDirectories(dir.resolve("sibling"));
        Files.createDirectories(project.resolve("src/main/java/demo"));
        Files.writeString(project.resolve("src/main/java/demo/Main.java"), """
            package demo;

            public final class Main {
                public static void main(String[] args) {
                }
            }
            """);
        Files.writeString(project.resolve("mjm.toml"), """
            [project]
            name = "demo"
            version = "0.1.0"
            main = "demo.Main"

            [repos]
            mine = "mjm:%s"

            [deps]
            "gadget" = "mine:0.9.0"
            """.formatted(base));
        return project;
    }

    private static byte[] validJar() throws IOException {
        Path jar = Files.createTempFile("fixture", ".jar");
        try (var out = new java.util.zip.ZipOutputStream(Files.newOutputStream(jar))) {
            out.putNextEntry(new java.util.zip.ZipEntry("META-INF/MANIFEST.MF"));
            out.write("Manifest-Version: 1.0\n".getBytes(StandardCharsets.UTF_8));
            out.closeEntry();
        }
        return Files.readAllBytes(jar);
    }

    // ------------------------------------------------------------------

    private void serve(byte[] body, String path) {
        routes.put(path, body);
    }

    private String start() throws IOException {
        server = HttpServer.create(new InetSocketAddress("localhost", 0), 0);
        server.createContext("/", exchange -> {
            String path = exchange.getRequestURI().getPath();
            if (exchange.getRequestMethod().equals("PUT")) {
                routes.put(path, exchange.getRequestBody().readAllBytes());
                puts.add(path);
                exchange.sendResponseHeaders(201, -1);
                exchange.close();
                return;
            }
            byte[] body = routes.get(path);
            if (body == null) {
                exchange.sendResponseHeaders(404, -1);
                exchange.close();
                return;
            }
            exchange.sendResponseHeaders(200, body.length);
            try (var out = exchange.getResponseBody()) {
                out.write(body);
            }
        });
        server.start();
        return "http://localhost:" + server.getAddress().getPort();
    }
}
