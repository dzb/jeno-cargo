package com.jujin.jeno.cli;

import com.jujin.jeno.store.Paths;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** {@code jeno doctor}: names before schema, never a fallback to the old mj files. */
class DoctorCommandTest {

    @TempDir
    Path root;

    @BeforeEach
    void isolatePaths() {
        Paths.useForTesting(root.resolve("cache/store"), root.resolve("cache/sources"),
                root.resolve("state/locks"));
    }

    @AfterEach
    void restorePaths() {
        Paths.resetForTesting();
    }

    @Test
    void aHealthySingleProjectIsOk() throws Exception {
        Path project = Files.createDirectories(root.resolve("project"));
        manifest(project, "demo");
        lock(project);

        Result result = run(project);

        assertEquals(0, result.exit(), result.out() + result.err());
        assertTrue(result.out().contains("doctor: project"), result.out());
        assertTrue(result.out().contains("jeno.toml (demo@0.1.0)"), result.out());
        assertTrue(result.out().contains("jeno.lock (0 artifact(s))"), result.out());
        assertTrue(result.out().contains("doctor: ok"), result.out());
    }

    @Test
    void legacyOldFilesAreNamedButNeverTreatedAsAFallback() throws Exception {
        Path project = Files.createDirectories(root.resolve("legacy"));
        Files.writeString(project.resolve("mjm.toml"), """
                [project]
                name = "old"
                version = "2.0.2"
                """);
        Files.writeString(project.resolve("mjm.lock"), "# generated by old\n");

        Result result = run(project);

        assertEquals(1, result.exit());
        assertTrue(result.out().contains("found an mjm-era project file"), result.out());
        assertTrue(result.out().contains("found an mjm-era lock file"), result.out());
        assertTrue(result.out().contains("mv mjm.toml jeno.toml"), result.out());
        assertTrue(result.out().contains("no jeno.toml"), result.out());
        assertTrue(result.out().contains("no jeno.lock — run jeno lock"), result.out());
        assertTrue(result.out().contains("doctor: problems found"), result.out());
    }

    @Test
    void aMissingLockNamesTheNextAction() throws Exception {
        Path project = Files.createDirectories(root.resolve("project"));
        manifest(project, "demo");

        Result result = run(project);

        assertEquals(1, result.exit());
        assertTrue(result.out().contains("no jeno.lock — run jeno lock"), result.out());
    }

    @Test
    void aWorkspaceChecksEveryModule() throws Exception {
        Path workspace = Files.createDirectories(root.resolve("workspace"));
        Path core = Files.createDirectories(workspace.resolve("libs/core"));
        Path web = Files.createDirectories(workspace.resolve("apps/web"));
        manifest(core, "core");
        lock(core);
        manifest(web, "web");
        Files.writeString(workspace.resolve("jeno.ws.toml"), """
                [ws]
                modules = ["libs/core", "apps/web"]
                """);

        Result result = run(workspace);

        assertEquals(1, result.exit());
        assertTrue(result.out().contains("doctor: workspace"), result.out());
        assertTrue(result.out().contains("module: libs/core"), result.out());
        assertTrue(result.out().contains("module: apps/web"), result.out());
        assertTrue(result.out().contains("no jeno.lock — run jeno lock"), result.out());
    }

    @Test
    void jsonWorkspaceReportsEveryModuleAndOneSummary() throws Exception {
        Path workspace = Files.createDirectories(root.resolve("workspace"));
        Path core = Files.createDirectories(workspace.resolve("libs/core"));
        Path web = Files.createDirectories(workspace.resolve("apps/web"));
        manifest(core, "core");
        lock(core);
        manifest(web, "web");
        Files.writeString(workspace.resolve("jeno.ws.toml"), """
                [ws]
                modules = ["libs/core", "apps/web"]
                """);

        Result result = run(workspace, "--json");

        assertEquals(1, result.exit());
        var rootJson = com.jujin.freeway.commons.json.JsonUtils.parseObject(
                result.out().strip());
        assertEquals("doctor", rootJson.getString("command"));
        assertEquals("failed", rootJson.getString("status"));
        assertEquals("all", rootJson.getObject("workspace").getString("mode"));
        assertEquals(2, rootJson.getArray("modules").size());
        var summary = rootJson.getObject("summary");
        assertEquals(2, summary.getInt("modules"));
        assertEquals(1, summary.getInt("failedModules"));
        var diagnostics = rootJson.getArray("diagnostics");
        boolean lockMissing = false;
        for (Object value : diagnostics.toList()) {
            if (value instanceof java.util.Map<?, ?> diagnostic
                    && "lock-missing".equals(diagnostic.get("code"))) {
                lockMissing = true;
            }
        }
        assertTrue(lockMissing, result.out());
    }

    @Test
    void argumentsAreUsageErrors() {
        Result result = run(root, "--bogus");

        assertEquals(2, result.exit());
        assertTrue(result.err().contains("doctor takes no arguments"), result.err());
    }

    @Test
    void jsonReportsModulesChecksAndLocalPaths() throws Exception {
        Path project = Files.createDirectories(root.resolve("project"));
        manifest(project, "demo");
        lock(project);

        Result result = run(project, "--json");

        assertEquals(0, result.exit(), result.out() + result.err());
        var rootJson = com.jujin.freeway.commons.json.JsonUtils.parseObject(
                result.out().strip());
        assertEquals("doctor", rootJson.getString("command"));
        assertEquals("ok", rootJson.getString("status"));
        assertEquals("single", rootJson.getObject("workspace").getString("mode"));
        var modules = rootJson.getArray("modules");
        assertEquals(1, modules.size());
        var module = modules.getObject(0);
        assertEquals(".", module.getString("module"));
        assertEquals("ok", module.getString("status"));
        assertTrue(module.getArray("checks").size() >= 3, result.out());
        boolean declarationsSkipped = module.getArray("checks").toList().stream()
                .anyMatch(value -> value instanceof java.util.Map<?, ?> check
                        && "declarations".equals(check.get("id"))
                        && "skipped".equals(check.get("status")));
        assertTrue(declarationsSkipped, result.out());
        assertTrue(result.out().contains("run jeno lock --check"), result.out());
    }

    @Test
    void aMalformedManifestNamesTheFileOnlyOnce() throws Exception {
        Path project = Files.createDirectories(root.resolve("broken"));
        Files.writeString(project.resolve("jeno.toml"), "not = [valid\n");

        Result result = run(project);

        assertEquals(1, result.exit());
        assertTrue(result.out().contains("jeno.toml:"), result.out());
        assertFalse(result.out().contains("jeno.toml: jeno.toml:"), result.out());
    }

    // ------------------------------------------------------------------

    private static void manifest(Path dir, String name) throws Exception {
        Files.writeString(dir.resolve("jeno.toml"), """
                [project]
                name = "%s"
                version = "0.1.0"
                """.formatted(name));
    }

    private static void lock(Path dir) throws Exception {
        Files.writeString(dir.resolve("jeno.lock"),
                "# generated by jeno — commit to version control, do not edit by hand\n");
    }

    private static Result run(Path projectDir, String... args) {
        PrintStream originalOut = System.out;
        PrintStream originalErr = System.err;
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        int exit;
        try {
            System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
            System.setErr(new PrintStream(err, true, StandardCharsets.UTF_8));
            exit = new DoctorCommand(projectDir).execute(List.of(args));
        } finally {
            System.setOut(originalOut);
            System.setErr(originalErr);
        }
        return new Result(exit, out.toString(StandardCharsets.UTF_8),
                err.toString(StandardCharsets.UTF_8));
    }

    private record Result(int exit, String out, String err) {}
}
