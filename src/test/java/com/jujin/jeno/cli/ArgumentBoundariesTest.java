package com.jujin.jeno.cli;

import com.jujin.jeno.store.ArtifactStore;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** {@code --} ends jeno's options, and {@code run} stops eating program flags. */
class ArgumentBoundariesTest {

    @TempDir
    Path dir;

    private ArtifactStore store;
    private Path project;

    @BeforeEach
    void setUp() throws Exception {
        ProjectLock.useRoot(dir.resolve(".locks"));
        com.jujin.jeno.store.Paths.useForTesting(dir.resolve(".cache/store"),
                dir.resolve(".cache/sources"), dir.resolve(".locks"));
        com.jujin.jeno.resolve.ArtifactLocations.useProjectRoot(dir);
        store = new ArtifactStore(dir.resolve(".cache/store"));
        project = dir.resolve("proj");
        Files.createDirectories(project.resolve("src/main/java/app"));
        Files.writeString(project.resolve("jeno.toml"), """
            [project]
            name = "proj"
            version = "0.1.0"
            main = "app.Main"
            """);
        Files.writeString(project.resolve("jeno.lock"),
                "# generated by jeno — commit to version control, do not edit by hand\n");
        Files.writeString(project.resolve("src/main/java/app/Main.java"), """
            package app;

            public final class Main {
                public static void main(String[] args) throws Exception {
                    java.nio.file.Files.writeString(
                            java.nio.file.Path.of("args.txt"), String.join("|", args));
                }
            }
            """);
        assertEquals(0, new BuildCommand(store, project).execute(List.of()));
        resetOffline();
    }

    @AfterEach
    void tearDown() {
        resetOffline();
        ProjectLock.useUserRoot();
        com.jujin.jeno.store.Paths.resetForTesting();
        com.jujin.jeno.resolve.ArtifactLocations.useProjectRoot(Path.of("").toAbsolutePath());
    }

    @Test
    void runKeepsProgramFlagsAfterTheTarget() {
        CommandRunner runner = new CommandRunner(List.of(new RunCommand(store, project)));

        assertEquals(0, runner.run("run", "app.Main", "--offline"));
        assertEquals("--offline", argsSeen());

        assertEquals(0, runner.run("run", "--offline", "app.Main"));
        assertEquals("", argsSeen(), "the flag was jeno's, the program got nothing");

        assertEquals(0, runner.run("run", "app.Main", "--", "--offline"));
        assertEquals("--offline", argsSeen());

        assertEquals(0, runner.run("run", "app.Main", "--module", "x"));
        assertEquals("--module|x", argsSeen(), "--module after the target is the program's");
    }

    @Test
    void theTerminatorAlsoFeedsStrictCommands() {
        CommandRunner runner = new CommandRunner(List.of(new BuildCommand(store, project)));

        Result result = run(runner, "build", "--", "--offline");

        assertEquals(2, result.exit(), "the tail is a positional argument to build");
        assertTrue(result.err().contains("build takes no arguments"), result.err());
    }

    @Test
    void topLevelHelpIsNotAnErrorButRunOwnsItsHelp() {
        Result help = run(new CommandRunner(List.of()), "--help");

        assertEquals(0, help.exit());
        assertTrue(help.out().contains("usage: jeno <command> [args]"), help.out());

        CommandRunner runner = new CommandRunner(List.of(new RunCommand(store, project)));
        assertEquals(0, runner.run("run", "app.Main", "--", "--help"));
        assertEquals("--help", argsSeen(), "after --, --help belongs to the program");
    }

    @Test
    void topLevelHelpGroupsCommandsByRole() {
        CommandRunner runner = new CommandRunner(List.of(
                stub("init", "start a project", Command.Category.PROJECT),
                stub("build", "compile sources", Command.Category.BUILD),
                stub("doctor", "diagnose the project", Command.Category.INSPECT)));

        Result help = run(runner, "--help");

        assertEquals(0, help.exit());
        assertTrue(help.out().contains("Project"), help.out());
        assertTrue(help.out().contains("Build & run"), help.out());
        assertTrue(help.out().contains("Inspect"), help.out());
        assertTrue(help.out().contains("Global flags"), help.out());
        assertTrue(help.out().contains("Run 'jeno <command> --help'"), help.out());
    }

    // ------------------------------------------------------------------

    private String argsSeen() {
        try {
            return Files.readString(project.resolve("args.txt"));
        } catch (IOException e) {
            throw new AssertionError("the program did not run", e);
        }
    }

    private static Result run(CommandRunner runner, String... args) {
        PrintStream originalOut = System.out;
        PrintStream originalErr = System.err;
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        int exit;
        try {
            System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
            System.setErr(new PrintStream(err, true, StandardCharsets.UTF_8));
            exit = runner.run(args);
        } finally {
            System.setOut(originalOut);
            System.setErr(originalErr);
        }
        return new Result(exit, out.toString(StandardCharsets.UTF_8),
                err.toString(StandardCharsets.UTF_8));
    }

    private static void resetOffline() {
        try {
            var field = ArtifactStore.class.getDeclaredField("offline");
            field.setAccessible(true);
            field.set(null, false);
        } catch (ReflectiveOperationException e) {
            throw new AssertionError("cannot reset the offline flag", e);
        }
    }

    private static Command stub(String name, String summary, Command.Category category) {
        return new Command() {
            @Override
            public String name() {
                return name;
            }

            @Override
            public Command.Category category() {
                return category;
            }

            @Override
            public String summary() {
                return summary;
            }

            @Override
            public CommandCapabilities capabilities() {
                return CommandCapabilities.builder().build();
            }

            @Override
            public int execute(List<String> args) {
                return 0;
            }
        };
    }

    private record Result(int exit, String out, String err) {}
}
