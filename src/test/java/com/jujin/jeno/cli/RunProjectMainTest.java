package com.jujin.jeno.cli;

import com.jujin.jeno.store.ArtifactStore;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** {@code jeno run} with no argument runs {@code [project].main}. */
class RunProjectMainTest {

    @TempDir
    Path dir;

    private ArtifactStore store;

    @BeforeEach
    void setUp() throws Exception {
        ProjectLock.useRoot(dir.resolve(".locks"));
        store = new ArtifactStore(dir.resolve("store"));
    }

    @AfterEach
    void tearDown() {
        ProjectLock.useUserRoot();
    }

    @Test
    void noArgumentRunsTheDeclaredMain() throws Exception {
        project("app.Main");
        assertEquals(0, new BuildCommand(store, dir).execute(List.of()));

        assertEquals(0, new RunCommand(store, dir).execute(List.of()));

        assertEquals("from-main", Files.readString(dir.resolve("from-main.txt")).strip());
    }

    @Test
    void anExplicitClassWinsOverTheDeclaredMain() throws Exception {
        project("app.Main");
        assertEquals(0, new BuildCommand(store, dir).execute(List.of()));

        assertEquals(0, new RunCommand(store, dir).execute(List.of("app.Other")));

        assertEquals("from-arg", Files.readString(dir.resolve("from-arg.txt")).strip());
    }

    @Test
    void noMainAndNoArgumentIsAUsageErrorThatNamesTheField() throws Exception {
        project(null);

        Result result = run();

        assertEquals(2, result.exit());
        assertTrue(result.err().contains("[project].main"), result.err());
        assertTrue(result.err().contains("jeno run <main-class>"), result.err());
    }

    @Test
    void aDirectoryWithoutAManifestStillReportsTheMissingFile() throws Exception {
        Result result = run();

        assertEquals(1, result.exit(), "the missing file outranks the usage hint");
        assertTrue(result.err().contains("no jeno.toml"), result.err());
    }

    // ------------------------------------------------------------------

    private void project(String main) throws IOException {
        Files.createDirectories(dir.resolve("src/main/java/app"));
        Files.writeString(dir.resolve("jeno.toml"), """
            [project]
            name = "consumer"
            version = "0.1.0"
            %s
            """.formatted(main == null ? "" : "main = \"" + main + "\""));
        Files.writeString(dir.resolve("src/main/java/app/Main.java"), """
            package app;

            public final class Main {
                public static void main(String[] args) throws Exception {
                    java.nio.file.Files.writeString(
                            java.nio.file.Path.of("from-main.txt"), "from-main");
                }
            }
            """);
        Files.writeString(dir.resolve("src/main/java/app/Other.java"), """
            package app;

            public final class Other {
                public static void main(String[] args) throws Exception {
                    java.nio.file.Files.writeString(
                            java.nio.file.Path.of("from-arg.txt"), "from-arg");
                }
            }
            """);
        Files.writeString(dir.resolve("jeno.lock"),
                "# generated by jeno — commit to version control, do not edit by hand\n");
    }

    private Result run() {
        PrintStream originalOut = System.out;
        PrintStream originalErr = System.err;
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        int exit;
        try {
            System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
            System.setErr(new PrintStream(err, true, StandardCharsets.UTF_8));
            exit = new RunCommand(store, dir).execute(List.of());
        } finally {
            System.setOut(originalOut);
            System.setErr(originalErr);
        }
        return new Result(exit, out.toString(StandardCharsets.UTF_8),
                err.toString(StandardCharsets.UTF_8));
    }

    private record Result(int exit, String out, String err) {}
}
