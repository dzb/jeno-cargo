package com.jujin.jeno.resolve;

import com.jujin.jeno.project.Species;
import com.jujin.jeno.store.LockFileReader;
import com.jujin.jeno.store.LockedArtifact;
import com.jujin.jeno.store.StoreException;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * jeno.lock's serialization (SPEC.md §4): id-sorted rows, both digests, and the
 * URL leaf's missing metadata slot.
 */
class LockFileTest {

    /** A stub digest source: deterministic, url-derived, obviously fake. */
    private static String stubSha(String url) {
        return String.format("%064x", url.chars().sum()).substring(0, 64);
    }

    private static ResolvedGraph.ResolvedArtifact centralJar(String groupPath, String artifactId,
                                                             String version, int depth,
                                                             boolean declared) {
        return new ResolvedGraph.ResolvedArtifact(groupPath.replace('/', '.') + ":" + artifactId,
                version, Species.CENTRAL, "central",
                "https://repo.maven.apache.org/maven2/" + groupPath + "/" + version + "/"
                        + artifactId + "-" + version + ".jar",
                "https://repo.maven.apache.org/maven2/" + groupPath + "/" + version + "/"
                        + artifactId + "-" + version + ".pom",
                depth, declared);
    }

    @Test
    void aGiteeRowExplainsItsMigration() {
        String lock = """
            [[artifacts]]
            id = "acme:lib"
            version = "1.0.0"
            source = "gitee:acme/lib"
            url = "https://gitee.com/acme/lib/releases/download/v1.0.0/lib-1.0.0.jar"
            sha256 = "%s"
            depth = 1
            """.formatted("a".repeat(64));

        StoreException error = assertThrows(StoreException.class,
                () -> LockFileReader.read(lock));

        assertTrue(error.getMessage().contains("gitee: species was removed"),
                error.getMessage());
        assertTrue(error.getMessage().contains("run jeno lock"), error.getMessage());
    }

    @Test
    void serializesSortedRowsWithBothDigests() {
        // The resolver sorts by id; the lockfile keeps that order as given.
        ResolvedGraph graph = new ResolvedGraph(
                List.of(
                        centralJar("com/example", "lib-a", "1.0.0", 1, true),
                        centralJar("org/example", "lib-b", "1.1.0", 2, false)),
                List.of(centralJar("com/example", "lib-a", "1.0.0", 1, true)),
                Map.of());

        String lock = LockFile.serialize(graph, LockFileTest::stubSha);

        assertTrue(lock.startsWith("# generated by jeno —"),
                "the header names the tool that wrote it, got: " + lock);
        assertTrue(lock.contains("# jeno-lockfile-version: 3"), lock);
        assertTrue(lock.indexOf("com.example:lib-a") < lock.indexOf("org.example:lib-b"),
                "rows are sorted by id (SPEC.md §4.2)");
        assertEquals(2, lock.split("\\[\\[artifacts]]", -1).length - 1, "one row per artifact");
        assertTrue(lock.contains("depth = 2"), "each row carries its depth");
        assertTrue(lock.contains("meta-sha256 = "), "both digests are pinned");
        // the lock must parse with jeno's own TOML subset
        com.jujin.freeway.commons.toml.TomlUtils.parse(lock);
    }

    @Test
    void v3MakesJenoTheDefaultAndMarksMavenExplicitly() {
        ResolvedGraph.ResolvedArtifact jenoNetwork = new ResolvedGraph.ResolvedArtifact(
                "freeway-commons", "2.0.2", Species.NAMED,
                "jeno:https://dzb.github.io/freeway/",
                "https://dzb.github.io/freeway/freeway-commons/2.0.2/freeway-commons-2.0.2.jar",
                "https://dzb.github.io/freeway/freeway-commons/2.0.2/freeway-commons-2.0.2.jeno.toml",
                1, true);
        ResolvedGraph.ResolvedArtifact jenoLocal = new ResolvedGraph.ResolvedArtifact(
                "gadget", "0.9.0", Species.NAMED, "jeno:local:../vendor",
                "file:vendor/gadget/0.9.0/gadget-0.9.0.jar",
                "file:vendor/gadget/0.9.0/gadget-0.9.0.jeno.toml", 1, true);
        ResolvedGraph.ResolvedArtifact mavenNetwork = new ResolvedGraph.ResolvedArtifact(
                "com.example:lib", "1.0.0", Species.CENTRAL, "https://nexus.corp/repository/",
                "https://nexus.corp/repository/com/example/lib/1.0.0/lib-1.0.0.jar",
                "https://nexus.corp/repository/com/example/lib/1.0.0/lib-1.0.0.pom",
                1, true);
        ResolvedGraph.ResolvedArtifact mavenLocal = new ResolvedGraph.ResolvedArtifact(
                "com.example:local-lib", "1.0.0", Species.CENTRAL, "local:../maven-vendor",
                "file:../maven-vendor/com/example/local-lib/1.0.0/local-lib-1.0.0.jar",
                "file:../maven-vendor/com/example/local-lib/1.0.0/local-lib-1.0.0.pom",
                1, true);
        ResolvedGraph graph = new ResolvedGraph(
                List.of(jenoNetwork, jenoLocal, mavenNetwork, mavenLocal),
                List.of(), Map.of());

        String lock = LockFile.serialize(graph, LockFileTest::stubSha);

        assertTrue(lock.contains("source = \"https://dzb.github.io/freeway/\""), lock);
        assertTrue(lock.contains("source = \"local:../vendor\""), lock);
        assertTrue(lock.contains("source = \"maven:https://nexus.corp/repository/\""), lock);
        assertTrue(lock.contains("source = \"maven:local:../maven-vendor\""), lock);
        assertFalse(lock.contains("jeno:"),
                "the new lock file must never expose the internal jeno: spelling");

        List<LockedArtifact> rows = LockFileReader.read(lock);
        assertEquals("jeno:https://dzb.github.io/freeway/", rows.get(0).source());
        assertEquals("jeno:local:../vendor", rows.get(1).source());
        assertEquals("https://nexus.corp/repository/", rows.get(2).source());
        assertEquals("local:../maven-vendor", rows.get(3).source());
    }

    @Test
    void v3RejectsTheOldJenoPrefix() {
        String lock = """
            # jeno-lockfile-version: 3
            [[artifacts]]
            id = "gadget"
            version = "0.9.0"
            source = "jeno:https://dzb.github.io/freeway/"
            url = "https://dzb.github.io/freeway/gadget/0.9.0/gadget-0.9.0.jar"
            sha256 = "%s"
            depth = 1
            """.formatted("a".repeat(64));

        StoreException error = assertThrows(StoreException.class,
                () -> LockFileReader.read(lock));
        assertTrue(error.getMessage().contains("remove the jeno: prefix"), error.getMessage());
    }

    @Test
    void legacyLockVersionsRemainReadOnlyMigrationInput() {
        String row = """
            # jeno-lockfile-version: 2
            [[artifacts]]
            id = "com.example:lib"
            version = "1.0.0"
            source = "https://nexus.corp/repository/"
            url = "https://nexus.corp/repository/com/example/lib/1.0.0/lib-1.0.0.jar"
            sha256 = "%s"
            depth = 1

            [[artifacts]]
            id = "gadget"
            version = "0.9.0"
            source = "jeno:https://dzb.github.io/freeway/"
            url = "https://dzb.github.io/freeway/gadget/0.9.0/gadget-0.9.0.jar"
            sha256 = "%s"
            depth = 1
            """.formatted("a".repeat(64), "b".repeat(64));

        List<LockedArtifact> rows = LockFileReader.read(row);

        assertEquals("https://nexus.corp/repository/", rows.get(0).source());
        assertEquals("jeno:https://dzb.github.io/freeway/", rows.get(1).source());
    }

    @Test
    void aUrlLeafHasNoMetadataDigest() {
        ResolvedGraph graph = new ResolvedGraph(
                List.of(new ResolvedGraph.ResolvedArtifact("vendored", "0.9",
                        Species.URL, "url",
                        "https://cdn.example.com/vendored-0.9.jar",
                        null, 1, true)),
                List.of(), Map.of());
        String lock = LockFile.serialize(graph, LockFileTest::stubSha);

        assertTrue(lock.contains("source = \"url\""));
        assertFalse(lock.contains("meta-sha256"), "a leaf has no metadata to pin");
    }

    @Test
    void lockfileVersionMarkerIsUniqueAndComesBeforeArtifacts() {
        String header = """
            # generated by jeno
            # jeno-lockfile-version: 3
            """;
        String row = """
            [[artifacts]]
            id = "com.example:lib-a"
            version = "1.0.0"
            source = "central"
            url = "https://repo.maven.apache.org/maven2/com/example/lib-a/1.0.0/lib-a-1.0.0.jar"
            sha256 = "%s"
            depth = 1
            """.formatted("a".repeat(64));

        assertTrue(LockFileReader.read(header + row).size() == 1);
        StoreException late = assertThrows(StoreException.class,
                () -> LockFileReader.read(row + "# jeno-lockfile-version: 3\n"));
        assertTrue(late.getMessage().contains("must precede [[artifacts]]"), late.getMessage());

        StoreException duplicate = assertThrows(StoreException.class,
                () -> LockFileReader.read(header + "# jeno-lockfile-version: 3\n" + row));
        assertTrue(duplicate.getMessage().contains("duplicate lockfile version marker"),
                duplicate.getMessage());
    }

    @Test
    void quotesInUrlsSurviveTheRoundTrip() {
        ResolvedGraph graph = new ResolvedGraph(
                List.of(new ResolvedGraph.ResolvedArtifact("weird", "1.0",
                        Species.URL, "url",
                        "https://cdn.example.com/a\"b\\c.jar",
                        null, 1, true)),
                List.of(), Map.of());
        String lock = LockFile.serialize(graph, url -> stubSha(url));

        com.jujin.freeway.commons.toml.TomlUtils.parse(lock);
        assertTrue(lock.contains("\\\""), "the quote is escaped");
    }

    @Test
    void apiRowsRoundTripAndFutureLockVersionsAreRefused() {
        ResolvedGraph graph = new ResolvedGraph(
                List.of(new ResolvedGraph.ResolvedArtifact("com.example:lib-a", "1.0.0",
                        Species.CENTRAL, "central",
                        "https://repo.maven.apache.org/maven2/com/example/lib-a/1.0.0/lib-a-1.0.0.jar",
                        "https://repo.maven.apache.org/maven2/com/example/lib-a/1.0.0/lib-a-1.0.0.pom",
                        1, false, Scope.MAIN, true)),
                List.of(), Map.of());

        String lock = LockFile.serialize(graph, LockFileTest::stubSha);
        assertTrue(lock.contains("api = true"), lock);
        assertEquals(true, LockFileReader.read(lock).get(0).api());

        String future = lock.replace("# jeno-lockfile-version: 3",
                "# jeno-lockfile-version: 999");
        StoreException unsupported = assertThrows(StoreException.class,
                () -> LockFileReader.read(future));
        assertTrue(unsupported.getMessage().contains("newer than this jeno supports"),
                unsupported.getMessage());
    }
}
